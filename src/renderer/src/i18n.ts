const messages: Record<Lang, Record<string, string>> = { 'zh-CN': zhCN, 'en-US': enUS }

export function t(key: string, params?: Record<string, string | number | undefined>): string {
  let s = messages[lang.value][key] ?? messages['zh-CN'][key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v))
    }
  }
  return s
}

export function setLang(l: Lang): void {
  lang.value = l
  document.documentElement.lang = l
}

export function currentLang(): Lang {
  return lang.value
}
